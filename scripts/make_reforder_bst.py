#!/usr/bin/env python3
"""Derive sn-basic-reforder.bst from sn-basic.bst so entries are numbered in
citation order rather than alphabetically.

Why: the Journal of Sustainable Metallurgy CSL style (dependent on
springer-basic-brackets) declares a numeric citation format and its
<bibliography> element carries NO <sort>, so CSL numbers references in the
order they are first cited.  sn-basic.bst instead presorts on
label+author+title, which produces alphabetical numbering -- e.g. the Kroll
1937 paper that opens the Introduction came out as [9].  Reviewers read the
list against the text, so citation order is the correct rendering for this
journal.

The fix is confined to the two sort-key assignments.  presort and bib.sort.order
each build an alphabetical sort.key$, and the style runs SORT twice, so both must
be neutralised: a constant sort.key$ makes each SORT a no-op, and BibTeX reads
.bib entries in citation order, so the surviving order is citation order.
sort.label is still computed because the author-year branches reference it.

Only those two blocks are touched; every formatting function is inherited
verbatim.
"""

import io
import sys

SRC = "sn-basic.bst"
DST = "sn-basic-reforder.bst"

with io.open(SRC, encoding="latin-1") as fh:
    bst = fh.read()

# ---- 1. presort: stop building an alphabetical key ------------------------
old = """FUNCTION {presort}
{ calc.label
  label sortify
  "    "
  *
  type$ "book" =
  type$ "inbook" =
  or
    'author.editor.sort
    { type$ "proceedings" =
        'editor.sort
        'author.sort
      if$
    }
  if$
  #1 entry.max$ substring$
  'sort.label :=
  sort.label
  *
  "    "
  *
  title field.or.null
  sort.format.title
  *
  #1 entry.max$ substring$
  'sort.key$ :=
}"""

new = """FUNCTION {presort}
{ calc.label
  label sortify
  'sort.label :=
  % Citation-order numbering: a constant sort.key$ turns the following SORT
  % into a no-op, so BibTeX's citation-read order survives.
  "" 'sort.key$ :=
}"""

if bst.count(old) != 1:
    print("ERROR [presort]: not matched exactly once (found %d)" % bst.count(old))
    sys.exit(1)
bst = bst.replace(old, new)

# ---- 2. bib.sort.order: the second SORT must also be neutralised ----------
old2 = """{ sort.label
  "    "
  *
  year field.or.null sortify
  *
  "    "
  *
  title field.or.null
  sort.format.title
  *
  #1 entry.max$ substring$
  'sort.key$ :=
}
ITERATE {bib.sort.order}
SORT"""

new2 = """{ % Citation-order numbering: neutralise the second SORT as well, otherwise it
  % re-establishes alphabetical order after presort has been defeated.
  "" 'sort.key$ :=
}
ITERATE {bib.sort.order}
SORT"""

if bst.count(old2) != 1:
    print("ERROR [bib.sort.order]: not matched exactly once (found %d)" % bst.count(old2))
    sys.exit(1)
bst = bst.replace(old2, new2)

# The header comment must state what this file is, so a future reader does not
# mistake it for the pristine Springer style.
banner = """% sn-basic-reforder.bst -- sn-basic.bst with citation-order numbering.
%
% Generated by scripts/make_reforder_bst.py from the unmodified sn-basic.bst
% shipped with the Springer Nature sn-jnl class.  The ONLY change is that the
% two sort-key assignments (presort, bib.sort.order) are replaced by constants,
% so BibTeX's SORT calls preserve citation order.  All formatting functions are
% untouched.

"""
if not bst.startswith("%"):
    print("ERROR: unexpected bst header")
    sys.exit(1)
bst = banner + bst

with io.open(DST, "w", encoding="latin-1", newline="\n") as fh:
    fh.write(bst)

print("wrote %s (%d bytes)" % (DST, len(bst)))
